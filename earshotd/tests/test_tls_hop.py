GOOD = "0123456789abcdef" * 4
HEALTH = b"GET /v1/health HTTP/1.1\r\nHost: earshotd\r\nConnection: close\r\n\r\n"

# Runs app.main in a child. With "fd" it is started the way systemd would: the listening socket
# as fd 3, with LISTEN_FDS and LISTEN_PID. With "bind" it binds listen itself. Only the worker
# (it loads models) is stubbed; uvicorn and the TLS context are real.
CHILD = """
import os, sys
from types import SimpleNamespace
from earshotd import app, worker

mode = sys.argv[1]
worker.start = lambda config: SimpleNamespace(status=None)
if mode == "fd":
    os.dup2(int(sys.argv[2]), 3)
    os.environ["LISTEN_FDS"] = "1"
    os.environ["LISTEN_PID"] = str(os.getpid())
app.main()
"""


def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


@pytest.fixture(scope="module")
def certs(tmp_path_factory):
    """The server pair and two proxy pairs, generated by the deploy scripts."""
    root = tmp_path_factory.mktemp("hop-certs")
    return (
        make_server_tls(root),
        make_proxy_cert(root, "proxy1"),
        make_proxy_cert(root, "proxy2"),
    )


def write_config(tmp_path: Path, port: int, certs) -> Path:
    server, proxy1, proxy2 = certs
    cfg = tmp_path / "earshotd.toml"
    cfg.write_text(
        f'data_dir = "{tmp_path / "data"}"\nlisten = "127.0.0.1:{port}"\n'
        f'tls_cert = "{server / "server.crt"}"\ntls_key = "{server / "server.key"}"\n'
        f'tls_proxy_certs = ["{proxy1 / "proxy.crt"}", "{proxy2 / "proxy.crt"}"]\n'
        f'[[tokens]]\ntoken = "{GOOD}"\nscope = "read"\n'
    )
    cfg.chmod(0o600)
    return cfg


def spawn(tmp_path: Path, certs, mode: str, held: socket.socket | None, port: int):
    cfg = write_config(tmp_path, port, certs)
    env = {k: v for k, v in os.environ.items() if not k.startswith("LISTEN_")}
    env["EARSHOTD_CONFIG"] = str(cfg)
    args = [sys.executable, "-c", CHILD, mode]
    pass_fds: tuple[int, ...] = ()
    if held is not None:
        args.append(str(held.fileno()))
        pass_fds = (held.fileno(),)
    return subprocess.Popen(
        args,
        env=env,
        pass_fds=pass_fds,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.PIPE,
        text=True,
    )


def fetch(
    port: int,
    server_crt: Path,
    client: tuple[Path, Path] | None = None,
    *,
    max_tls: ssl.TLSVersion | None = None,
    plain: bool = False,
) -> bytes:
    """Everything the server sent back to GET /v1/health: empty when no handshake or no HTTP."""
    try:
        with socket.create_connection(("127.0.0.1", port), timeout=5) as raw:
            conn: socket.socket = raw
            if not plain:
                context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
                context.load_verify_locations(server_crt)
                if client:
                    context.load_cert_chain(*client)
                if max_tls:
                    context.maximum_version = max_tls
                conn = context.wrap_socket(raw, server_hostname="earshotd")
            conn.sendall(HEALTH)
            data = b""
            while chunk := conn.recv(65536):
                data += chunk
            return data
    except (OSError, ssl.SSLError):
        return b""


def body_of(response: bytes) -> bytes:
    return response.split(b"\r\n\r\n", 1)[1]


def proxy_pair(directory: Path) -> tuple[Path, Path]:
    return directory / "proxy.crt", directory / "proxy.key"


def wait_until_serving(p: subprocess.Popen, port: int, certs) -> None:
    """Block until the child answers the first proxy's health check, or fail with its stderr."""
    deadline = time.monotonic() + 30
    while time.monotonic() < deadline and p.poll() is None:
        if fetch(port, certs[0] / "server.crt", proxy_pair(certs[1])).startswith(
            b"HTTP/1.1 200"
        ):
            return
        time.sleep(0.2)
    p.kill()
    pytest.fail(f"earshotd never answered over TLS: {p.communicate()[1]}")


def stop(p: subprocess.Popen) -> str:
    if p.poll() is None:
        p.kill()
    return p.communicate()[1]


def check_pinning(port: int, certs, tmp_path: Path, *, own_key: bool) -> None:
    server, proxy1, proxy2 = certs
    crt = server / "server.crt"
    ok = fetch(port, crt, proxy_pair(proxy1))
    assert ok.startswith(b"HTTP/1.1 200")
    assert json.loads(body_of(ok)) == {"ok": True}
    second = fetch(port, crt, proxy_pair(proxy2))
    assert second.startswith(b"HTTP/1.1 200")
    assert json.loads(body_of(second)) == {"ok": True}
    if own_key:
        own = fetch(port, crt, (server / "server.crt", server / "server.key"))
        assert own.startswith(b"HTTP/1.1 200")
        assert json.loads(body_of(own)) == {"ok": True}
    # the same subject as the first proxy, but another key: nothing pins it
    rogue = make_proxy_cert(tmp_path, "rogue")
    assert fetch(port, crt, proxy_pair(rogue)) == b""
    assert fetch(port, crt) == b""
    assert fetch(port, crt, proxy_pair(proxy1), max_tls=ssl.TLSVersion.TLSv1_2) == b""
    assert fetch(port, crt, plain=True) == b""


def test_passed_socket_serves_only_pinned_tls13_clients(tmp_path, certs):
    held = socket.socket()
    held.bind(("127.0.0.1", 0))
    held.listen()
    port = held.getsockname()[1]
    p = spawn(tmp_path, certs, "fd", held, port)
    try:
        wait_until_serving(p, port, certs)
        check_pinning(port, certs, tmp_path, own_key=True)
    finally:
        err = stop(p)
        held.close()
    assert "Traceback" not in err, err


def test_a_bound_listen_serves_the_same_mutual_tls(tmp_path, certs):
    port = free_port()
    p = spawn(tmp_path, certs, "bind", None, port)
    try:
        wait_until_serving(p, port, certs)
        server, proxy1, _ = certs
        assert fetch(port, server / "server.crt", proxy_pair(proxy1)).startswith(
            b"HTTP/1.1 200"
        )
        assert fetch(port, server / "server.crt", plain=True) == b""
    finally:
        err = stop(p)
    assert "Traceback" not in err, err


# app.main with create_app, worker.start and uvicorn.run replaced by recorders.
@pytest.fixture
def recorded(monkeypatch):
    calls: list[tuple[str, dict]] = []
    import uvicorn

    def create_app(config):
        calls.append(("create_app", {}))
        return SimpleNamespace(state=SimpleNamespace())

    def start(config):
        calls.append(("worker.start", {}))
        return SimpleNamespace(status=None)

    monkeypatch.setattr(app_module, "create_app", create_app)
    monkeypatch.setattr(worker, "start", start)
    monkeypatch.setattr(
        uvicorn, "run", lambda app, **kw: calls.append(("uvicorn.run", kw))
    )
    monkeypatch.delenv("LISTEN_FDS", raising=False)
    monkeypatch.delenv("LISTEN_PID", raising=False)
    return calls


def set_config(monkeypatch, cfg: Path) -> None:
    monkeypatch.setenv("EARSHOTD_CONFIG", str(cfg))


def test_an_exposed_key_stops_main_before_anything_loads(
    tmp_path, certs, recorded, monkeypatch, capsys
):
    server, proxy1, proxy2 = certs
    mine = tmp_path / "server"
    shutil.copytree(server, mine)
    (mine / "server.key").chmod(0o644)
    cfg = write_config(tmp_path, free_port(), (mine, proxy1, proxy2))
    set_config(monkeypatch, cfg)
    with pytest.raises(SystemExit) as e:
        app_module.main()
    assert e.value.code not in (None, 0)
    message = str(e.value.code)
    assert str(mine / "server.key") in message and "0644" in message
    assert recorded == []


def test_the_plain_http_opt_in_runs_without_a_context_and_says_so(
    tmp_path, recorded, monkeypatch, capsys
):
    cfg = tmp_path / "earshotd.toml"
    cfg.write_text(
        f'data_dir = "{tmp_path / "data"}"\nlisten = "0.0.0.0:{free_port()}"\n'
        f"insecure_plain_http = true\n"
        f'[[tokens]]\ntoken = "{GOOD}"\nscope = "read"\n'
    )
    cfg.chmod(0o600)
    set_config(monkeypatch, cfg)
    app_module.main()
    (run,) = [kw for name, kw in recorded if name == "uvicorn.run"]
    assert "ssl_context_factory" not in run and not any(
        k.startswith("ssl") for k in run
    )
    lines = [
        ln for ln in capsys.readouterr().err.splitlines() if "insecure_plain_http" in ln
    ]
    assert len(lines) == 1 and "plain http" in lines[0]
