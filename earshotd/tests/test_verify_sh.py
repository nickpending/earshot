def probe(
    tmp_path, config: Path, addr: str
) -> tuple[subprocess.CompletedProcess, Path]:
    log = tmp_path / "curl.log"
    shim_dir = tmp_path / "shim"
    shim_dir.mkdir(exist_ok=True)
    shim = shim_dir / "curl"
    shim.write_text(SHIM % {"log": log, "curl": shutil.which("curl")})
    shim.chmod(0o755)
    env = {**os.environ, "PATH": f"{shim_dir}:{os.environ['PATH']}"}
    done = subprocess.run(
        ["bash", "-c", 'source "$1" && worker_state "$2" "$3"', "bash"]
        + [str(VERIFY), str(config), addr],
        check=False,
        env=env,
        capture_output=True,
        text=True,
        timeout=60,
    )
    return done, log


def test_worker_probe_reads_status_with_the_read_token_off_the_command_line(served):
    addr, seen, tmp_path = served
    done, log = probe(tmp_path, tmp_path / "earshotd.toml", addr)
    assert done.returncode == 0, done.stderr
    assert done.stdout.strip() == "running"
    logged = log.read_text()
    assert RD not in logged and RD not in done.stderr
    assert "stdin:pipe" in logged
    assert ("/v1/status", f"Bearer {RD}") in seen


def test_worker_probe_without_a_read_token_fails_and_never_asks_health(
    tmp_path, served
):
    addr, seen, _ = served
    cfg = tmp_path / "upload-only.toml"
    cfg.write_text(
        f'data_dir = "{tmp_path}"\n[[tokens]]\ntoken = "{UP}"\nscope = "upload"\n'
    )
    done, _ = probe(tmp_path, cfg, addr)
    assert done.returncode != 0
    assert "read token" in done.stderr
    assert seen == []


def local_probes(config: Path, port: int) -> subprocess.CompletedProcess:
    """verify.sh sourced, its local probes run against `config` with the test interpreter."""
    return subprocess.run(
        ["bash", "-c", 'source "$1" && local_probes "$2" "$3"', "bash"]
        + [str(VERIFY), str(config), str(port)],
        check=False,
        env={**os.environ, "EARSHOT_PY": sys.executable},
        capture_output=True,
        text=True,
        timeout=60,
    )


def test_local_probes_without_tls_settings_use_plain_http_as_before(served):
    addr, seen, tmp_path = served
    done = local_probes(tmp_path / "earshotd.toml", int(addr.split(":")[1]))
    assert done.returncode == 0, done.stderr
    assert done.stdout.splitlines() == ["ok   local health 200", "ok   worker running"]
    assert {p for p, _ in seen} == {"/v1/health", "/v1/status"}


def test_local_probes_with_tls_settings_go_over_mutual_tls_and_prove_both_refusals(
    tmp_path, certs
):
    server, proxy = certs
    context = tls.server_context(tls_config(tmp_path, server, proxy))
    with Served(tmp_path, context) as s:
        lines = (
            f'tls_cert = "{server / "server.crt"}"\ntls_key = "{server / "server.key"}"\n'
            f'tls_proxy_certs = ["{proxy / "proxy.crt"}"]\n'
        )
        cfg = _write_config(tmp_path, lines, s.port)
        done = local_probes(cfg, s.port)
    assert done.returncode == 0, done.stderr
    assert done.stdout.splitlines() == [
        "ok   local health 200",
        "ok   worker running",
        "ok   handshake without a client certificate refused",
        "ok   plain http refused",
    ]
    assert RD not in done.stdout + done.stderr


def verify(
    role: str, env: dict[str, str] | None = None, shims: Path | None = None
) -> subprocess.CompletedProcess:
    """verify.sh `role` with the verify variables cleared, then `env` set, `shims` first on PATH."""
    base = {k: v for k, v in os.environ.items() if not k.startswith("EARSHOT_VERIFY_")}
    if shims:
        base["PATH"] = f"{shims}:{base['PATH']}"
    return subprocess.run(
        ["bash", str(VERIFY), role],
        check=False,
        env={**base, **(env or {})},
        capture_output=True,
        text=True,
        timeout=60,
    )


def at(addr: str) -> dict[str, str]:
    host, port = addr.split(":")
    return {"EARSHOT_VERIFY_HOST": host, "EARSHOT_VERIFY_PORT": port}


def proxy_role(addr: str, tls_dir: Path | None = None) -> subprocess.CompletedProcess:
    env = at(addr)
    if tls_dir:
        env["EARSHOT_VERIFY_TLS_DIR"] = str(tls_dir)
    return verify("proxy", env)


def logging_shims(tmp_path: Path) -> tuple[Path, Path, Path]:
    """A dir holding a curl and an ssh that log each call: (dir, curl log, ssh log)."""
    shim_dir = tmp_path / "role-shims"
    shim_dir.mkdir()
    curl_log, ssh_log = tmp_path / "role-curl.log", tmp_path / "role-ssh.log"
    curl = shim_dir / "curl"
    curl.write_text(SHIM % {"log": curl_log, "curl": shutil.which("curl")})
    ssh = shim_dir / "ssh"
    ssh.write_text(f'#!/bin/bash\necho "$@" >> "{ssh_log}"\n')
    for shim in (curl, ssh):
        shim.chmod(0o755)
    return shim_dir, curl_log, ssh_log


@pytest.fixture
def proxy_dir(tmp_path, certs):
    """What the proxy holds: its own proxy.crt and proxy.key, and the server's server.crt."""
    server, proxy_pair = certs
    out = tmp_path / "proxy-tls"
    out.mkdir()
    for src in (
        proxy_pair / "proxy.crt",
        proxy_pair / "proxy.key",
        server / "server.crt",
    ):
        shutil.copy(src, out / src.name)
    return out


@pytest.mark.parametrize("role", ["proxy", "outside"])
@pytest.mark.parametrize(
    "env", [{}, {"EARSHOT_VERIFY_HOST": ""}], ids=["unset", "empty"]
)
def test_c1_a_role_that_probes_refuses_until_the_server_address_is_named(
    tmp_path, proxy_dir, role, env
):
    shims, curl_log, ssh_log = logging_shims(tmp_path)
    done = verify(role, {**env, "EARSHOT_VERIFY_TLS_DIR": str(proxy_dir)}, shims)
    assert done.returncode == 1, done.stdout + done.stderr
    assert done.stdout.startswith("FAIL EARSHOT_VERIFY_HOST is not set")
    assert not curl_log.exists() and not ssh_log.exists()


