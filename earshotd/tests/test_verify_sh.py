# Logs what verify.sh hands curl (argv, and whether stdin is a pipe), then runs the real curl.
SHIM = """#!/bin/bash
{
  printf 'argv:'; printf ' %%s' "$@"; printf '\\n'
  if [ -p /dev/stdin ]; then echo stdin:pipe; else echo stdin:none; fi
} >> "%(log)s"
exec "%(curl)s" "$@"
"""


def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def _write_config(tmp_path: Path, extra: str = "", port: int | None = None) -> Path:
    cfg = tmp_path / "earshotd.toml"
    listen = f'listen = "127.0.0.1:{port}"\n' if port else ""
    cfg.write_text(
        f'data_dir = "{tmp_path / "data"}"\n{listen}{extra}'
        f'[[tokens]]\ntoken = "{UP}"\nscope = "upload"\n'
        f'[[tokens]]\ntoken = "{RD}"\nscope = "read"\n'
    )
    cfg.chmod(0o600)
    return cfg


class Served:
    """A real earshotd app on uvicorn, plain or behind a TLS context; records requests seen."""

    def __init__(self, tmp_path: Path, context: ssl.SSLContext | None = None):
        app = create_app(load(_write_config(tmp_path)))
        app.state.worker_status = worker.Status()
        self.seen: list[tuple[str, str | None]] = []

        async def recording(scope, receive, send):
            if scope["type"] == "http":
                headers = dict(scope["headers"])
                auth = headers.get(b"authorization")
                self.seen.append((scope["path"], auth.decode() if auth else None))
            await app(scope, receive, send)

        self.port = _free_port()
        self.server = uvicorn.Server(
            uvicorn.Config(
                recording,
                host="127.0.0.1",
                port=self.port,
                log_level="warning",
                server_header=False,
                ssl_context_factory=(lambda *_: context) if context else None,
            )
        )
        self.thread = threading.Thread(target=self.server.run, daemon=True)

    def __enter__(self) -> Self:
        self.thread.start()
        deadline = time.monotonic() + 10
        while not self.server.started and time.monotonic() < deadline:
            time.sleep(0.05)
        assert self.server.started
        return self

    def __exit__(self, *exc) -> None:
        self.server.should_exit = True
        self.thread.join(10)

    @property
    def addr(self) -> str:
        return f"127.0.0.1:{self.port}"


