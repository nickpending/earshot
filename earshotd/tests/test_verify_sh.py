@pytest.mark.parametrize("listening", [True, False])
def test_c3_outside_role_is_ok_only_when_the_direct_connection_gets_no_answer(
    tmp_path, served, listening
):
    addr = served[0] if listening else f"127.0.0.1:{_free_port()}"
    shims, _, ssh_log = logging_shims(tmp_path)
    done = verify("outside", at(addr), shims)
    if listening:
        assert done.returncode == 1
        assert f"FAIL outside host reached {addr} directly" in done.stdout
    else:
        assert done.returncode == 0, done.stdout
        assert "ok   outside host direct connection refused or dropped" in done.stdout
    assert not ssh_log.exists()


def test_c2_proxy_role_proves_the_tokenless_surface_over_mutual_tls(
    tmp_path, certs, proxy_dir
):
    server, proxy = certs
    context = tls.server_context(tls_config(tmp_path, server, proxy))
    with Served(tmp_path, context) as s:
        done = proxy_role(s.addr, proxy_dir)
        seen = {p for p, _ in s.seen}
    assert done.returncode == 0, done.stdout
    assert "FAIL" not in done.stdout
    assert {"ok   handshake without a client certificate refused"} <= set(
        done.stdout.splitlines()
    )
    assert any("plain http" in ln for ln in done.stdout.splitlines())
    assert seen == {"/v1/health", "/v1/status", "/v1/openapi.json"}


