def test_c2_proxy_role_fails_a_leaky_health(tmp_path, certs, proxy_dir):
    class Leaky(http.server.BaseHTTPRequestHandler):
        def do_GET(self):
            body = b'{"ok": true, "pages": 3}'
            self.send_response(200)  # also sends a Server header
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, *args):
            pass

    server, proxy = certs
    context = tls.server_context(tls_config(tmp_path, server, proxy))
    httpd = http.server.HTTPServer(("127.0.0.1", 0), Leaky)
    httpd.socket = context.wrap_socket(httpd.socket, server_side=True)
    thread = threading.Thread(target=httpd.serve_forever, daemon=True)
    thread.start()
    try:
        done = proxy_role(f"127.0.0.1:{httpd.server_port}", proxy_dir)
    finally:
        httpd.shutdown()
        thread.join(10)
    assert done.returncode != 0
    assert "FAIL health body" in done.stdout
    assert "FAIL health response carries a Server header" in done.stdout
    assert "FAIL /v1/status" in done.stdout
    assert "FAIL /v1/openapi.json" in done.stdout
